"""The "built" part of files/spec/001-TomlSettings.md, made from files/fusionSettings.xml
(Task 51.5, user 2026-11-08).

The part between BUILT_START and BUILT_END is generated - every built setting, its type or
values, default, description and task. The rest of the file (designed, not built yet) is
written by hand.

    python tools/settings_doc.py      rewrite the generated part
    check.py runs settings_problems() reports it when out of date
"""

import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
XML = ROOT / 'files' / 'fusionSettings.xml'
DOC = ROOT / 'files' / 'spec' / '001-TomlSettings.md'
BUILT_START = '<!-- built:start - generated by tools/settings_doc.py, do not edit -->'
BUILT_END = '<!-- built:end -->'


def cell(text):
    return ' '.join((text or '').split()).replace('|', '/')


def kind(setting):
    t = setting.get('type')
    if t == 'choice':
        values = []
        for v in setting.findall('value'):
            values.append(f'`{v.text}`' + (' (reserved)' if v.get('reserved') == 'true' else ''))
        return ' / '.join(values)
    if t in ('int', 'int-or-max'):
        low = setting.get('min')
        extra = f', at least {low}' if low is not None else ''
        return ('`max` or a whole number' if t == 'int-or-max' else 'a whole number') + extra
    return t


def built_part():
    root = ET.parse(XML).getroot()
    out = [BUILT_START, '']
    count = 0
    for section in root.findall('section'):
        out.append(f"#### [{section.get('name')}] - {cell(section.get('description'))}")
        out.append('')
        out.append('| Setting | Values | Default | What it does | Task |')
        out.append('|---|---|---|---|---|')
        for s in section.findall('setting'):
            count += 1
            out.append(f"| `{s.get('name')}` | {cell(kind(s))} | `{s.get('default')}` | "
                       f"{cell(s.findtext('description'))} | {s.get('task', '')} |")
        out.append('')
    out.insert(1, f'{count} built settings in {len(root.findall("section"))} sections.')
    out.append(BUILT_END)
    return '\n'.join(out)


def updated(text):
    start, end = text.index(BUILT_START), text.index(BUILT_END) + len(BUILT_END)
    return text[:start] + built_part() + text[end:]


def settings_problems():
    text = DOC.read_text(encoding='utf-8')
    if BUILT_START not in text or BUILT_END not in text:
        return [f'{DOC.relative_to(ROOT)}: the generated part is missing']
    if updated(text) != text:
        return [f'{DOC.relative_to(ROOT)}: out of date with files/fusionSettings.xml - run python tools/settings_doc.py']
    return []


def main():
    text = DOC.read_text(encoding='utf-8')
    new = updated(text)
    if new != text:
        DOC.write_text(new, encoding='utf-8', newline='\n')
        print(f'wrote     {DOC.relative_to(ROOT)}')
    else:
        print('up to date')
    return 0


if __name__ == '__main__':
    sys.exit(main())
